<?php

// Prepare files only. The caller owns backup, installation, nginx -t, reload and rollback.
const PREVIEW_CSP_VARIABLE = '$tc_document_preview_csp';

function previewPagePolicy(string $policy): string
{
    if ($policy === '' || preg_match('/["\\\\$\r\n\x00]/', $policy)) {
        throw new RuntimeException('Unsupported CSP quoting or variables.');
    }
    $directives = [];
    foreach (explode(';', $policy) as $directive) {
        $tokens = preg_split('/\s+/', trim($directive));
        $name = strtolower(array_shift($tokens));
        if ($name === '') {
            continue;
        }
        if (isset($directives[$name])) {
            throw new RuntimeException('Duplicate CSP directive.');
        }
        $directives[$name] = $tokens;
    }
    if (($directives['object-src'] ?? null) !== ["'none'"] || isset($directives['sandbox'])) {
        throw new RuntimeException('Expected object-src none and no global sandbox.');
    }
    // child-src blob: otherwise takes precedence over default-src for iframes.
    // Keep child-src/worker-src intact and authorize only same-origin frames explicitly.
    if (! isset($directives['frame-src'])) {
        $policy = rtrim($policy).(str_ends_with(rtrim($policy), ';') ? '' : ';')." frame-src 'self';";
        $directives['frame-src'] = ["'self'"];
    }
    foreach (['frame-src', 'img-src', 'connect-src'] as $name) {
        $sources = $directives[$name] ?? $directives['default-src'] ?? [];
        if (! in_array("'self'", $sources, true)) {
            throw new RuntimeException('The page CSP must already allow same-origin '.$name.'.');
        }
    }
    if (isset($directives['frame-ancestors']) && ! in_array("'self'", $directives['frame-ancestors'], true)) {
        throw new RuntimeException('The CSP must allow same-origin frame ancestors.');
    }

    return $policy;
}

function previewNginxMap(string $policy): string
{
    $policy = previewPagePolicy($policy);
    $pdfPolicy = preg_replace("/(^|;)(\\s*object-src\\s+)'none'(\\s*)(?=;|$)/i", "$1$2'self'$3", $policy);

    return '# Generated by document-preview-nginx.php; install in the http context only.'."\n"
        .'map "$upstream_http_x_tc_document_preview:$upstream_http_content_type" '.PREVIEW_CSP_VARIABLE." {\n"
        .'    default "'.$policy.'";'."\n"
        .'    "pdf:application/pdf" "'.$pdfPolicy.'";'."\n"
        ."}\n";
}

try {
    if ($argc < 4 || $argc > 5) {
        throw new RuntimeException('Usage: php document-preview-nginx.php INPUT_VHOST OUTPUT_VHOST OUTPUT_MAP [EXISTING_MAP]');
    }
    [$script, $input, $output, $mapOutput] = $argv;
    if (! is_file($input) || ! is_readable($input) || filesize($input) > 1024 * 1024
        || file_exists($output) || is_link($output) || file_exists($mapOutput) || is_link($mapOutput)
        || $output === $mapOutput) {
        throw new RuntimeException('Expected a readable input and two distinct new output files.');
    }
    $source = file_get_contents($input);
    $active = preg_replace('/^\h*#.*$/m', '', $source);
    if (preg_match_all('/\bserver\s*\{/', $active) !== 1
        || preg_match_all('~^\h*root\h+/var/www/TechCalendar-v2/public;\h*$~m', $active) !== 1
        || preg_match_all('/\badd_header\h+Content-Security-Policy\b/i', $active) !== 1
        || preg_match('/\b(?:more_set_headers|more_clear_headers)\b|\b(?:proxy|fastcgi)_hide_header\h+["\x27]?Content-Security-Policy\b/i', $active)
        || preg_match('/\badd_header\h+X-Frame-Options\h+["\x27]?DENY\b/i', $active)) {
        throw new RuntimeException('Unexpected vhost or conflicting security headers; manual review required.');
    }
    $pattern = '/^(\h*add_header\h+Content-Security-Policy\h+)("[^"\r\n]*"|\$tc_document_preview_csp)(\h+always;\h*)$/mi';
    if (preg_match_all($pattern, $active, $matches) !== 1) {
        throw new RuntimeException('Expected one double-quoted CSP with always, or the generated CSP variable.');
    }
    $value = $matches[2][0];
    if ($value === PREVIEW_CSP_VARIABLE) {
        $existing = $argv[4] ?? '';
        if (! is_file($existing) || ! is_readable($existing) || filesize($existing) > 16384) {
            throw new RuntimeException('An existing generated map is required for an already-patched vhost.');
        }
        $map = file_get_contents($existing);
        if (! preg_match('/^    default "([^"\r\n]+)";$/m', $map, $default)
            || $map !== previewNginxMap($default[1])) {
            throw new RuntimeException('Existing map differs from the generated format or policy.');
        }
    } else {
        $map = previewNginxMap(substr($value, 1, -1));
    }
    // Replace the exact active directive, leaving comments and every other header untouched.
    $directive = $matches[0][0];
    if (substr_count($source, $directive) !== 1) {
        throw new RuntimeException('Ambiguous CSP directive.');
    }
    $prepared = str_replace($directive, $matches[1][0].PREVIEW_CSP_VARIABLE.$matches[3][0], $source);
    $created = [];
    try {
        foreach ([$output => $prepared, $mapOutput => $map] as $path => $contents) {
            $handle = @fopen($path, 'x');
            if ($handle === false) {
                throw new RuntimeException('Cannot create output file.');
            }
            $created[] = $path;
            try {
                if (fwrite($handle, $contents) !== strlen($contents)) {
                    throw new RuntimeException('Incomplete output write.');
                }
            } finally {
                fclose($handle);
            }
        }
    } catch (Throwable $exception) {
        foreach ($created as $path) {
            unlink($path);
        }
        throw $exception;
    }
    echo "Prepared vhost and HTTP-context map. No installation or reload performed.\n";
} catch (Throwable $exception) {
    fwrite(STDERR, $exception->getMessage()."\n");
    exit(1);
}
